-- Captains' changes need the admin's approval (cosmetic ones, crest and jersey numbers, do not).
-- Pending changes live on the rows themselves; everything that already exists is approved.

-- A team created by a captain is "in review" until approved; a rename waits in pending_name; a deletion request
-- is marked with its date.
alter table teams add column approved boolean not null default true;
alter table teams add column created_at timestamp(6);
alter table teams add column pending_name varchar(255);
alter table teams add column pending_name_at timestamp(6);
alter table teams add column deletion_requested_at timestamp(6);

-- A player added by a captain is pending until approved; a removal request is marked with its date.
alter table players add column approved boolean not null default true;
alter table players add column requested_at timestamp(6);
alter table players add column removal_requested_at timestamp(6);

-- registrations.approved already exists: a captain's registration starts not approved.
alter table registrations add column requested_at timestamp(6);

-- What the admin decided, so the captain can see it (the team may no longer exist: its name is kept).
create table request_decisions (
    id         bigint generated by default as identity primary key,
    team_id    bigint,
    team_name  varchar(255) not null,
    captain_id bigint,
    type       varchar(30)  not null,
    subject    varchar(255),
    approved   boolean      not null,
    reason     varchar(500),
    decided_at timestamp(6) not null,
    constraint fk_request_decisions_team foreign key (team_id) references teams (id) on delete set null,
    constraint fk_request_decisions_captain foreign key (captain_id) references users (id) on delete set null
);
create index ix_request_decisions_captain on request_decisions (captain_id);
