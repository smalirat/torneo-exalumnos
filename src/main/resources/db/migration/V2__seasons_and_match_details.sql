-- Seasons (a year groups Apertura/Clausura) and extra match data coming from the league's Excel.

create table seasons (
    id          bigint generated by default as identity primary key,
    season_year integer not null,
    constraint uk_seasons_year unique (season_year)
);

alter table tournaments add column season_id bigint;
alter table tournaments add column stage varchar(20);
alter table tournaments add constraint fk_tournaments_season foreign key (season_id) references seasons (id);
alter table tournaments add constraint ck_tournaments_stage check (stage in ('APERTURA', 'CLAUSURA'));
alter table tournaments add constraint uk_tournaments_season_stage unique (season_id, stage);
create index ix_tournaments_season on tournaments (season_id);

-- "Fecha N" number, label of special rounds ("Interzonal", "Repetición en zonas"),
-- field ("Anexo", "Siberia"), pitch number and a free note ("no se presentó, no avisó")
alter table matches add column round integer;
alter table matches add column round_label varchar(80);
alter table matches add column venue varchar(60);
alter table matches add column pitch varchar(20);
alter table matches add column notes varchar(500);
