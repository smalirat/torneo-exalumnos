-- Data that comes from the league's Excel: annual player stats, sanctions, accumulated yellow cards,
-- historic champions. "source" says where the current value came from (EXCEL import or WEB edit) so the
-- importer can flag conflicts with what was edited on the web.

alter table matches add column source varchar(10);
alter table matches add constraint ck_matches_source check (source in ('EXCEL', 'WEB'));

-- Annual totals per player (Goleadores / Figuras / Imbatibles sheets); each value is optional
create table player_season_stats (
    id             bigint generated by default as identity primary key,
    season_id      bigint not null,
    player_id      bigint not null,
    team_id        bigint not null,
    goals          integer,
    figure_count   integer,
    goals_conceded integer,
    source         varchar(10),
    constraint uk_player_season_stats unique (season_id, player_id),
    constraint ck_player_season_stats_source check (source in ('EXCEL', 'WEB')),
    constraint fk_player_season_stats_season foreign key (season_id) references seasons (id),
    constraint fk_player_season_stats_player foreign key (player_id) references players (id),
    constraint fk_player_season_stats_team foreign key (team_id) references teams (id)
);
create index ix_player_season_stats_player on player_season_stats (player_id);

-- Suspensions (Expulsados block): red card, double yellow or yellow accumulation
create table sanctions (
    id                bigint generated by default as identity primary key,
    season_id         bigint       not null,
    tournament_id     bigint,
    player_id         bigint       not null,
    team_id           bigint       not null,
    type              varchar(30)  not null,
    matches_suspended integer      not null,
    matches_served    integer      not null,
    status            varchar(20)  not null,
    notes             varchar(500),
    source            varchar(10),
    constraint ck_sanctions_type check (type in ('DIRECT_RED', 'DOUBLE_YELLOW', 'YELLOW_ACCUMULATION', 'OTHER')),
    constraint ck_sanctions_status check (status in ('PENDING', 'SERVED', 'TRIBUNAL')),
    constraint ck_sanctions_source check (source in ('EXCEL', 'WEB')),
    constraint fk_sanctions_season foreign key (season_id) references seasons (id),
    constraint fk_sanctions_tournament foreign key (tournament_id) references tournaments (id),
    constraint fk_sanctions_player foreign key (player_id) references players (id),
    constraint fk_sanctions_team foreign key (team_id) references teams (id)
);
create index ix_sanctions_season on sanctions (season_id);
create index ix_sanctions_player on sanctions (player_id);

-- Accumulated yellow cards per tournament (Amonestados blocks): 4 = 1 match, 8 = 2 matches
create table yellow_card_tallies (
    id            bigint generated by default as identity primary key,
    tournament_id bigint  not null,
    player_id     bigint  not null,
    team_id       bigint  not null,
    yellow_cards  integer not null,
    source        varchar(10),
    constraint uk_yellow_card_tallies unique (tournament_id, player_id),
    constraint ck_yellow_card_tallies_source check (source in ('EXCEL', 'WEB')),
    constraint fk_yellow_card_tallies_tournament foreign key (tournament_id) references tournaments (id),
    constraint fk_yellow_card_tallies_player foreign key (player_id) references players (id),
    constraint fk_yellow_card_tallies_team foreign key (team_id) references teams (id)
);
create index ix_yellow_card_tallies_player on yellow_card_tallies (player_id);

-- Historic champions per year and category (HISTORIA sheet)
create table champions (
    id            bigint generated by default as identity primary key,
    champion_year integer     not null,
    category_name varchar(20) not null,
    team_id       bigint      not null,
    source        varchar(10),
    constraint uk_champions_year_category unique (champion_year, category_name),
    constraint ck_champions_source check (source in ('EXCEL', 'WEB')),
    constraint fk_champions_team foreign key (team_id) references teams (id)
);
create index ix_champions_team on champions (team_id);
