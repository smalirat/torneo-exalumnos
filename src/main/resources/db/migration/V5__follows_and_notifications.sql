-- Users follow tournaments; notifications belong to a tournament and are shown to its followers.
create table follows (
    id            bigint generated by default as identity primary key,
    user_id       bigint       not null references users (id) on delete cascade,
    tournament_id bigint       not null references tournaments (id) on delete cascade,
    created_at    timestamp(6) not null,
    constraint uq_follows_user_tournament unique (user_id, tournament_id)
);

-- Old rows were never shown to anyone and pointed to tournaments through a free-text target
delete from notifications;
alter table notifications drop column target;
alter table notifications add column tournament_id bigint not null references tournaments (id) on delete cascade;
create index ix_notifications_tournament on notifications (tournament_id, created_at);

-- Everything newer than this is unread for the user
alter table users add column notifications_seen_at timestamp(6);
